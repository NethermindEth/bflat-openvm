// u256 vector guest: runs every zkvm_u256_* shim in openvm_intrinsics.S against
// precomputed results, on the OpenVM runner rather than only linking.
//
// guest.cs proves the symbols link; it never executes them, so a wrong funct7,
// a swapped register or a misread operand would still pass there. This guest
// executes each shim and compares limb for limb. Every operation also runs with
// the result written over its first operand and over its second, the in-place
// forms a caller uses on a stack slot, which only hold if the instruction reads
// both operands before it writes.
//
// The public output is 32 bytes: the number of mismatches, then the number of
// checks, each a little-endian u64, then zeros. CI asserts zero mismatches.
//
// Semantics, from OpenVM's bigint circuit on the rv64 line: add, sub and mul wrap
// modulo 2^256; the shifts take their count from the low byte of the second
// operand, so a count of 256 shifts by 0; slt and sltu write 1 or 0.

using System.Runtime.InteropServices;

internal static unsafe class U256
{
    [DllImport("__Internal")] private static extern void zkvm_u256_add(ulong* r, ulong* a, ulong* b);
    [DllImport("__Internal")] private static extern void zkvm_u256_sub(ulong* r, ulong* a, ulong* b);
    [DllImport("__Internal")] private static extern void zkvm_u256_xor(ulong* r, ulong* a, ulong* b);
    [DllImport("__Internal")] private static extern void zkvm_u256_or(ulong* r, ulong* a, ulong* b);
    [DllImport("__Internal")] private static extern void zkvm_u256_and(ulong* r, ulong* a, ulong* b);
    [DllImport("__Internal")] private static extern void zkvm_u256_sll(ulong* r, ulong* a, ulong* b);
    [DllImport("__Internal")] private static extern void zkvm_u256_srl(ulong* r, ulong* a, ulong* b);
    [DllImport("__Internal")] private static extern void zkvm_u256_sra(ulong* r, ulong* a, ulong* b);
    [DllImport("__Internal")] private static extern void zkvm_u256_slt(ulong* r, ulong* a, ulong* b);
    [DllImport("__Internal")] private static extern void zkvm_u256_sltu(ulong* r, ulong* a, ulong* b);
    [DllImport("__Internal")] private static extern void zkvm_u256_mul(ulong* r, ulong* a, ulong* b);
    [DllImport("__Internal")] private static extern void write_output(ulong* output, nuint size);

    internal static void Run(ulong op, ulong* r, ulong* a, ulong* b)
    {
        switch (op)
        {
            case 0: zkvm_u256_add(r, a, b); break;
            case 1: zkvm_u256_sub(r, a, b); break;
            case 2: zkvm_u256_xor(r, a, b); break;
            case 3: zkvm_u256_or(r, a, b); break;
            case 4: zkvm_u256_and(r, a, b); break;
            case 5: zkvm_u256_sll(r, a, b); break;
            case 6: zkvm_u256_srl(r, a, b); break;
            case 7: zkvm_u256_sra(r, a, b); break;
            case 8: zkvm_u256_slt(r, a, b); break;
            case 9: zkvm_u256_sltu(r, a, b); break;
            case 10: zkvm_u256_mul(r, a, b); break;
        }
    }

    internal static void Publish(ulong mismatches, ulong checks)
    {
        // ulong locals keep the buffer 8-byte aligned, as the output window requires.
        ulong* output = stackalloc ulong[4];
        output[0] = mismatches;
        output[1] = checks;
        output[2] = 0;
        output[3] = 0;
        write_output(output, 32);
    }
}

